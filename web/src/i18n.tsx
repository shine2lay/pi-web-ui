export type Translate = (key: keyof typeof en, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
	/** Always "en": pi-web-ui speaks English only (the Chinese UI and the language menu were removed). */
	locale: Locale;
	t: Translate;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const LOCALE: Locale = "en";

export function LanguageProvider({ children }: { children: ReactNode }) {
	const t = useCallback<Translate>((key, vars) => {
		let str: string = en[key];
		if (vars) {
			for (const [k, v] of Object.entries(vars)) {
				str = str.replaceAll(`{${k}}`, String(v));
			}
		}
		return str;
	}, []);

	useEffect(() => {
		document.documentElement.lang = "en";
		// 标题由 App 统一维护（项目名优先，见 App.tsx 的 document.title effect）。
	}, []);

	const value = useMemo(() => ({ locale: LOCALE, t }), [t]);

	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
	const ctx = useContext(I18nContext);
	if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
	return ctx;
}

/** Convenience: translation function only. */
export function useT(): Translate {
	return useI18n().t;
}
